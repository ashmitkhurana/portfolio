import { chromium } from "playwright";
import { readFileSync } from "node:fs";
import path from "node:path";
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const out = path.join(root, "docs/ribbon/turns/paper2");
const pose = JSON.parse(readFileSync(path.join(root, "docs/ribbon/turns/paper/apex_candidate.json"), "utf8"));
const SX = 852 / 390, SY = 1846 / 844;
const [x0, y0, x1, y1] = [180, 530, 480, 760];
const clip = { x: x0 / SX, y: y0 / SY, width: (x1 - x0) / SX, height: (y1 - y0) / SY };
const b = await chromium.launch({ channel: "chromium", headless: true, args: ["--use-angle=metal", "--ignore-gpu-blocklist"] });
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 3 });
await ctx.addInitScript((p) => { window.__poseOverride = p; }, pose);
const page = await ctx.newPage();
await page.goto("http://localhost:4100/?tier=4", { waitUntil: "load" });
await page.waitForFunction(() => window.__ribbonState?.phase === "live", null, { timeout: 40000 });
await page.evaluate(() => document.fonts.ready);
await page.evaluate(() => window.scrollTo(0, 0));
await page.waitForTimeout(1500);
await page.evaluate(() => { const e = window.__ribbonState.engine; e.patchSettings({ post: { pixelRatioCap: 3 } }); e.applySettings(true); });
await page.waitForTimeout(1500);
await page.screenshot({ path: path.join(out, "engine_frontside_ref.png"), clip });
await page.waitForTimeout(1200);
await page.screenshot({ path: path.join(out, "engine_frontside_ref2.png"), clip });
const r = await page.evaluate(() => { const c = window.__ribbonState.engine.core; const m = c.mesh.material; const b = m.side; m.side = 2; m.needsUpdate = true;
  const dm = c.mesh.customDepthMaterial; return { before: b, depthSide: dm && dm.side, shadowSide: m.shadowSide }; });
console.log(r);
await page.waitForTimeout(1200);
await page.screenshot({ path: path.join(out, "engine_doubleside.png"), clip });
await page.evaluate(() => { const m = window.__ribbonState.engine.core.mesh.material; m.side = 0; m.needsUpdate = true; });
await page.waitForTimeout(1200);
await page.screenshot({ path: path.join(out, "engine_frontside_back.png"), clip });
await b.close();
